-- V12: Tenant Company Branding, Logo, Letterhead, Stamp & Receipt Template Profile

CREATE TABLE IF NOT EXISTS tenant_branding_profiles (
    tenant_id VARCHAR(64) PRIMARY KEY,
    legal_name VARCHAR(180) NOT NULL,
    trading_name VARCHAR(180) NOT NULL,
    tagline VARCHAR(240),
    tax_id_niu VARCHAR(80),
    rccm_number VARCHAR(80),
    cnps_employer_id VARCHAR(80),
    country_code VARCHAR(8) NOT NULL DEFAULT 'CM',
    default_currency VARCHAR(12) NOT NULL DEFAULT 'FCFA',
    vat_rate_pct DOUBLE PRECISION NOT NULL DEFAULT 19.25,
    address VARCHAR(255),
    city VARCHAR(120),
    phone VARCHAR(64),
    email VARCHAR(160),
    website VARCHAR(180),
    bank_name VARCHAR(160),
    bank_account_iban VARCHAR(120),
    mobile_money_merchant VARCHAR(180),
    primary_color_hex VARCHAR(16) NOT NULL DEFAULT '#0F172A',
    accent_color_hex VARCHAR(16) NOT NULL DEFAULT '#D97706',
    invoice_prefix VARCHAR(24) NOT NULL DEFAULT 'INV-',
    po_prefix VARCHAR(24) NOT NULL DEFAULT 'PO-',
    receipt_prefix VARCHAR(24) NOT NULL DEFAULT 'RCP-',
    payment_terms VARCHAR(255),
    letterhead_footer VARCHAR(300),
    receipt_header_note VARCHAR(180),
    receipt_footer_note VARCHAR(240),
    signatory_name VARCHAR(120),
    signatory_title VARCHAR(140),
    logo_data_url TEXT,
    stamp_data_url TEXT,
    updated_by VARCHAR(128),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
